"""국가 역법 표시 자료를 원본 호환 DLL에 제공한다. 작성: 최병호."""
import argparse
import csv
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]
KEY=re.compile(r'[a-z][a-z0-9_]*\Z')

def load(directory):
    def rows(name,columns):
        with (directory/name).open(encoding='utf-8',newline='') as source:
            reader=csv.DictReader(source)
            if reader.fieldnames!=columns.split(','):raise ValueError(f'Wrong columns: {name}')
            result=list(reader)
        if not result or any(None in row or any(v is None or not v for v in row.values()) for row in result):
            raise ValueError(f'Empty or malformed rows: {name}')
        keys=[row['key'] for row in result]
        if len(set(keys))!=len(keys) or any(not KEY.fullmatch(k) for k in keys):raise ValueError(f'Duplicate/invalid keys: {name}')
        return result
    calendars=rows('calendars.csv','key,name,year_offset')
    families=rows('families.csv','key,name,calendar,commands,ranks,offices,peerage,ship_style')
    countries=rows('countries.csv','id,key,name,family,native_power,native_camp,assets')
    calendar_keys={c['key'] for c in calendars};family_keys={f['key'] for f in families}
    for c in calendars:
        if not -10000<=int(c['year_offset'])<=10000:raise ValueError('Calendar offset out of range')
    for f in families:
        if f['calendar'] not in calendar_keys:raise ValueError('Unknown calendar')
        if any(not KEY.fullmatch(f[k]) for k in ('commands','ranks','offices','peerage','ship_style')):raise ValueError('Invalid system key')
    ids=set()
    for c in countries:
        identifier=int(c['id'])
        if not 0<identifier<=2147483647 or identifier in ids or c['family'] not in family_keys:raise ValueError('Invalid country identity/family')
        if not 0<=int(c['native_power'])<=4 or not 0<=int(c['native_camp'])<=1:raise ValueError('Unsupported native display code')
        if not KEY.fullmatch(c['assets']):raise ValueError('Invalid asset profile key')
        ids.add(identifier)
    return calendars,families,countries

def header(directory):
    calendars,families,countries=load(directory)
    def wide(value):
        if any(c in value for c in '\\"\n\r'):raise ValueError('Invalid display name')
        return 'L"'+value+'"'
    lines=['// Generated by tools/l10n/country_catalog.py. Author: 최병호.','#pragma once','namespace logh {',
           'struct CountryCalendar { const wchar_t* family; const wchar_t* name; int yearOffset; };',
           'static constexpr CountryCalendar countryCalendars[]={']
    by_key={c['key']:c for c in calendars}
    for f in families:
        c=by_key[f['calendar']]
        lines.append('    {'+wide(f['key'])+','+wide(c['name'])+','+c['year_offset']+'},')
    lines+=['};','struct CountryDisplay { unsigned id; unsigned calendar; };','static constexpr CountryDisplay countryDisplays[]={']
    indices={f['key']:i for i,f in enumerate(families)}
    for c in countries:lines.append('    {'+c['id']+','+str(indices[c['family']])+'},')
    lines+=['};','inline const CountryCalendar* countryCalendar(unsigned id) {',
            '    for(const auto& country:countryDisplays)if(country.id==id)return &countryCalendars[country.calendar];',
            '    return nullptr;','}','}','']
    return '\n'.join(lines)

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT/'config/countries')
    parser.add_argument('--header',type=Path,default=ROOT/'client-compat/country_catalog_data.h')
    args=parser.parse_args()
    args.header.write_text(header(args.source),encoding='utf-8',newline='\n')
